#!/usr/bin/env python3
"""
Differential-Jacobian comparison between PInv(SVD) and PInv(SVD)+Alloc.

The script generates exactly three two-panel figures:

Figure 1: differential-Jacobian rank maps
    left:  PInv(SVD)
    right: PInv(SVD)+Alloc

Figure 2: minimum-singular-value maps
    left:  PInv(SVD)
    right: PInv(SVD)+Alloc

Figure 3:
    left:  Delta sigma_min = sigma_min,heuristic - sigma_min,PInv
    right: horizontal-plane cross section (beta = 0 deg)

The differential allocation Jacobian is

    delta w = J_diff [delta f; delta alpha],

    J_diff = [A_f, A_alpha] in R^(6x8),

where

    A_f     = A_fixed B_f(alpha),
    A_alpha = A_fixed B_alpha(f, alpha).

A dimensionless Jacobian is used for singular-value analysis:

    J_bar = S_w J_diff S_u.

Rank is invariant to nonsingular scaling, whereas the numerical singular
values depend on the selected input/output scales.

Default vehicle:
    generic X-layout tiltable quadrotor
    arm length                 = 0.275 m
    mass                       = 3.039 kg
    yaw moment per thrust      = 0.0165 m
    heuristic thrust threshold = 1.5 N

An actual PhysParamBeetleOmni.yaml can be supplied with --yaml.
"""

